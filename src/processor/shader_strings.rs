#[repr(C)]
#[derive(Debug, Clone, Copy, Pod, Zeroable)]
pub(super) struct StringMeta {
    pub byte_offset: u32,
    pub byte_len: u32,
    pub scalar_len: u32,
    pub _padding: u32,
}

#[derive(Debug)]
pub(super) struct ShaderAssets {
    pub source: String,
    pub metadata: Vec<StringMeta>,
    pub words: Vec<u32>,
    pub byte_len: usize,
}

#[derive(Debug, Clone, Copy)]
struct StringDefinition {
    wgsl_name: &'static str,
    value: &'static str,
}

